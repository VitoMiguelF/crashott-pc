"""Generates runtime/kernel/import_list.inc from the symbols CrashPPC.lib needs but does not define.

Usage: python runtime/tools/gen_import_stubs.py build/CrashPPC.lib runtime/kernel/import_list.inc

Runs llvm-nm (from PATH or C:/Program Files/LLVM/bin), takes every undefined symbol that no
member of the library defines, and keeps the recompiled kernel/XAM imports (`__imp__<Name>`,
emitted by XenonRecomp as C++ functions). Anything else unresolved is printed so it can be
handled by hand (CRT symbols such as memcpy/_setjmp come from the static CRT).
"""
import os, re, shutil, subprocess, sys

def nm(lib, *flags):
    exe = shutil.which("llvm-nm") or r"C:\Program Files\LLVM\bin\llvm-nm.exe"
    out = subprocess.run([exe, *flags, lib], capture_output=True, text=True, check=True).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if not parts or line.endswith(":"):
            continue
        names.add(parts[-1])
    return names

def main():
    lib, out_path = sys.argv[1], sys.argv[2]
    unresolved = sorted(nm(lib, "-u") - nm(lib, "--defined-only"))
    imports, other = [], []
    for sym in unresolved:
        m = re.fullmatch(r"\?__imp__(\w+)@@YAXAEIAUPPCContext@@PEAE@Z", sym)
        (imports.append(m.group(1)) if m else other.append(sym))

    with open(out_path, "w", newline="\n") as f:
        f.write("// Generated by runtime/tools/gen_import_stubs.py from CrashPPC.lib. Do not edit.\n")
        f.write(f"// {len(imports)} xboxkrnl/xam imports referenced by the recompiled code.\n")
        for name in imports:
            f.write(f"GUEST_IMPORT({name})\n")

    print(f"{len(imports)} imports -> {out_path}")
    if other:
        print("other unresolved symbols (expected from the CRT):", " ".join(other))

if __name__ == "__main__":
    main()
